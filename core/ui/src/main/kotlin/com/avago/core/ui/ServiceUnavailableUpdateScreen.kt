/**
 * Full-screen blocker shown when the server reports this app's API contract version as
 * incompatible (plan §11: "service unavailable, please update the app"). There is no way past
 * it except updating; [onUpdate] should open the store listing.
 */
@Composable
fun ServiceUnavailableUpdateScreen(onUpdate: () -> Unit, modifier: Modifier = Modifier) {
    Surface(modifier = modifier.fillMaxSize(), color = MaterialTheme.colorScheme.background) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .safeDrawingPadding()
                .padding(horizontal = 32.dp),
            verticalArrangement = Arrangement.Center,
            horizontalAlignment = Alignment.CenterHorizontally,
        ) {
            Text(
                text = stringResource(R.string.v2_update_required_title),
                style = MaterialTheme.typography.headlineSmall,
                color = MaterialTheme.colorScheme.onBackground,
                textAlign = TextAlign.Center,
                modifier = Modifier.semantics { heading() },
            )
            Spacer(Modifier.height(12.dp))
            Text(
                text = stringResource(R.string.v2_update_required_message),
                style = MaterialTheme.typography.bodyLarge,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                textAlign = TextAlign.Center,
            )
            Spacer(Modifier.height(24.dp))
            Button(onClick = onUpdate, modifier = Modifier.fillMaxWidth()) {
                Text(stringResource(R.string.v2_update_required_action))
            }
        }
    }
}
